#!/usr/bin/env python3
"""Generate docs/cli.md from the click command tree.

  python3 scripts/gen_cli_reference.py          # rewrite docs/cli.md
  python3 scripts/gen_cli_reference.py --check  # exit 1 if docs/cli.md is stale

Rows are built from each parameter's declared fields (not click's help formatter), so the output
does not depend on the click version or the terminal width.
"""
from __future__ import annotations

import argparse
import inspect
import sys
from pathlib import Path

import click

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "docs" / "cli.md"
STABILITY = ROOT / "docs" / "stability.md"


def _cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ").strip()


def _type(param: click.Parameter) -> str:
    if isinstance(param.type, click.Choice):
        return " \\| ".join(f"`{c}`" for c in param.type.choices)
    if getattr(param, "is_flag", False):
        return "flag"
    return {"text": "text", "integer": "integer", "float": "number", "path": "path", "boolean": "boolean"}.get(
        param.type.name.lower(), param.type.name.lower()
    )


def _default(param: click.Parameter) -> str:
    value = param.default
    if not isinstance(value, (str, int, float, bool, type(None))):
        value = None  # click's "unset" sentinel in newer versions
    if getattr(param, "is_flag", False):
        return "off" if not value else "on"
    return "" if value in (None, "") else f"`{value}`"


def _options_table(command: click.Command) -> list[str]:
    rows = []
    for param in command.params:
        if isinstance(param, click.Argument):
            continue
        flags = ", ".join(f"`{o}`" for o in [*param.opts, *getattr(param, "secondary_opts", [])])
        env = f"`{param.envvar}`" if isinstance(param.envvar, str) else ""
        rows.append(
            f"| {flags} | {_type(param)} | {_default(param)} | {env} | {_cell(getattr(param, 'help', '') or '')} |"
        )
    if not rows:
        return []
    return ["| Option | Type | Default | Environment variable | Description |", "|---|---|---|---|---|", *rows, ""]


def _usage(command: click.Command, path: str) -> str:
    parts = [path]
    if command.params and any(isinstance(p, click.Option) for p in command.params):
        parts.append("[OPTIONS]")
    if isinstance(command, click.Group):
        parts.append("COMMAND [ARGS]...")
    parts.extend(p.human_readable_name.upper() for p in command.params if isinstance(p, click.Argument))
    return " ".join(parts)


def _section(command: click.Command, path: str, out: list[str]) -> None:
    out += [f"## `{path}`", ""]
    if command.help:
        # The help text is laid out for a terminal, so keep that layout. "\b" is click's
        # "do not rewrap this paragraph" marker and means nothing outside the terminal.
        text = inspect.cleandoc(command.help).replace("\b\n", "").replace("\b", "")
        out += ["```text", text.strip(), "```", ""]
    out += ["```", _usage(command, path), "```", ""]
    args = [p for p in command.params if isinstance(p, click.Argument)]
    if args:
        out += ["Arguments: " + ", ".join(f"`{a.human_readable_name.upper()}`" for a in args), ""]
    out += _options_table(command)
    if isinstance(command, click.Group):
        for name, sub in sorted(command.commands.items()):
            if not sub.hidden:
                _section(sub, f"{path} {name}", out)


def _exit_code_table() -> list[str]:
    lines = STABILITY.read_text(encoding="utf-8").splitlines()
    start = lines.index("## Exit codes")
    table = []
    for line in lines[start + 1:]:
        if line.startswith("|"):
            table.append(line)
        elif table:
            break
    return table


def render() -> str:
    from quin_scanner.cli import cli

    out = [
        "# Command-line reference",
        "",
        "<!-- Generated by scripts/gen_cli_reference.py from the click commands. Do not edit by hand. -->",
        "",
        "The CLI is a stable surface from 1.0: commands, options, defaults and exit codes follow the",
        "[stability policy](stability.md). `quin-scanner --version` prints the installed version and the report",
        "schema version. Run `quin-scanner COMMAND --help` for the same information in the terminal.",
        "",
        "## Exit codes",
        "",
        *_exit_code_table(),
        "",
    ]
    _section(cli, "quin-scanner", out)
    return "\n".join(out).rstrip() + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if docs/cli.md is not up to date")
    args = parser.parse_args(argv)
    text = render()
    if args.check:
        if not OUTPUT.is_file() or OUTPUT.read_text(encoding="utf-8") != text:
            print("docs/cli.md is stale: run python3 scripts/gen_cli_reference.py", file=sys.stderr)
            return 1
        return 0
    OUTPUT.write_text(text, encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
